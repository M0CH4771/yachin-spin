# ---------- せんべい：かじった跡のある丸いせんべい＋かたむけて貼ったのり ----------
@sp('senbei')
def _():
    s = S(True)
    s.disc(16, 16, 13.5, '#e0aa5a')
    for cx, cy, r in ((26, 6, 4), (29.5, 10.5, 3.6), (22.5, 3.5, 3)):           # かじった跡
        for X in range(32):
            for Y in range(32):
                if (X + .5 - cx) ** 2 + (Y + .5 - cy) ** 2 <= r * r: s.g[Y][X] = None
